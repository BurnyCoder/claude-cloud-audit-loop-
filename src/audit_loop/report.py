"""Generate reports/summary.md from the ledger and each audit report's front-matter.

Every number in the summary comes from these two files, so ``audit-loop report`` regenerates it.
"""

from pathlib import Path

COUNTS = ("claims_checked", "fixed", "unverifiable", "not_fixed")


def front_matter(path: Path) -> dict:
    """``key: value`` pairs between the leading ``---`` lines; integers parsed, rest kept as text."""
    lines = path.read_text(encoding="utf-8").splitlines() if path.exists() else []
    if not lines or lines[0].strip() != "---":
        return {}
    meta = {}
    for line in lines[1:]:
        if line.strip() == "---":
            break
        key, sep, value = line.partition(":")
        if sep:
            value = value.strip().strip("'\"")
            meta[key.strip()] = int(value) if value.lstrip("-").isdigit() else value
    return meta


def report_path(reports_dir: Path, slug: str, round_: int) -> Path:
    return reports_dir / "audits" / slug.split("/")[1] / f"round-{round_}.md"


def summary(entries: list[dict], reports_dir: Path, spend: dict | None = None, budget: float | None = None) -> str:
    """Markdown summary: one row per finished audit, totals, and spend."""
    final = {}  # (repo, round) -> last finished entry
    for e in entries:
        if e.get("status") not in (None, "started"):
            final[(e["repo"], e["round"])] = e
    rows, totals, drift = [], dict.fromkeys(COUNTS, 0), []
    cost_total = 0.0
    for (slug, rnd), e in sorted(final.items(), key=lambda kv: (kv[0][1], kv[1]["time"])):
        path = report_path(reports_dir, slug, rnd)
        meta = front_matter(path)
        counts = [meta.get(k) if isinstance(meta.get(k), int) else None for k in COUNTS]
        for k, v in zip(COUNTS, counts):
            totals[k] += v or 0
        cost = e.get("cost_usd")
        cost_total += cost or 0
        if str(meta.get("hf_card_drift", "")).lower() == "yes":
            drift.append(slug)
        pr = f"[PR]({e['pr']})" if e.get("pr") else ""
        link = f"[report]({path.relative_to(reports_dir).as_posix()})" if path.exists() else ""
        cells = [f"[{slug}](https://github.com/{slug})", str(rnd), e["status"], f"{cost:.2f}" if cost is not None else "",
                 *("" if v is None else str(v) for v in counts), " ".join(x for x in (pr, link) if x)]
        rows.append("| " + " | ".join(cells) + " |")
    out = ["# Audit summary", "", "Generated by `audit-loop report` from `ledger.jsonl` and the front-matter of "
           "`audits/<repo>/round-<n>.md`. Costs are list-price estimates from the session transcripts.", ""]
    if spend is not None:
        out += [f"- Session spend so far: **${spend['total']:.2f}**"
                + (f" of a ${budget:.2f} budget" if budget else "")
                + f" (orchestrator ${spend['main']:.2f}, subagents ${spend['total'] - spend['main']:.2f})"]
    out += [f"- Audits finished: **{len(rows)}**; attributed audit cost: **${cost_total:.2f}**",
            "- Totals: " + ", ".join(f"{k} **{v}**" for k, v in totals.items()), ""]
    out += ["| Repository | Round | Status | Cost (USD) | Claims checked | Fixed | Unverifiable | Not fixed | Links |",
            "|---|---|---|---|---|---|---|---|---|", *rows, ""]
    if drift:
        out += ["## Hugging Face cards that differ from the repository copy", "",
                "These hosted cards need re-uploading; each report gives the command.", "",
                *(f"- [{s}](https://github.com/{s})" for s in dict.fromkeys(drift)), ""]
    return "\n".join(out)
